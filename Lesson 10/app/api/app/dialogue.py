def demo_messages() -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = []
    index = 1
    for _, pairs in STAGES:
        for role, content in pairs:
            messages.append(
                {
                    "id": index,
                    "role": role,
                    "content": content,
                    "tokens": count_tokens(content),
                }
            )
            index += 1
    return messages


def demo_summaries() -> list[dict[str, Any]]:
    summaries: list[dict[str, Any]] = []
    offset = 1
    for number, (summary, pairs) in enumerate(STAGES, 1):
        count = len(pairs)
        summaries.append(
            {
                "id": number,
                "from_id": offset,
                "to_id": offset + count - 1,
                "content": summary,
                "tokens": count_tokens(summary),
            }
        )
        offset += count
    return summaries
